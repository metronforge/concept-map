import {
  mkdirSync,
  rmSync,
  writeFileSync,
  readFileSync,
  copyFileSync,
  cpSync,
} from "node:fs";
import { execFileSync } from "node:child_process";
import { cpus, platform, arch } from "node:os";
import { createHash } from "node:crypto";
import { build } from "rolldown";
import { layout, validateReferences } from "../../dist/layout/index.js";
import { dagreEngine } from "../../dist/layout/dagre.js";
import { elkEngine } from "../../dist/layout/elk.js";
import { bookMaps, stripGeometry } from "./maps.mjs";
import { coffeeManual } from "./coffee.mjs";
import { geometryMetrics } from "./metrics.mjs";
import { bundleSizes } from "./bundles.mjs";
import { page, graphSvg } from "./page.mjs";

const destination = "comparison-dist";
rmSync(destination, { recursive: true, force: true });
for (const dir of ["", "/data", "/svg", "/fonts"])
  mkdirSync(destination + dir, { recursive: true });
const pkg = JSON.parse(readFileSync("package.json", "utf8"));
const lock = readFileSync("package-lock.json");
const report = {
  generatedAt: new Date().toISOString(),
  revision: execFileSync("git", ["rev-parse", "HEAD"], {
    encoding: "utf8",
  }).trim(),
  dirty: !!execFileSync(
    "git",
    ["status", "--porcelain", "--untracked-files=no"],
    { encoding: "utf8" },
  ).trim(),
  environment: {
    node: process.version,
    platform: platform(),
    arch: arch(),
    cpu: cpus()[0]?.model,
  },
  versions: {
    dagre: pkg.devDependencies["@dagrejs/dagre"],
    elk: pkg.devDependencies.elkjs,
    zod: pkg.devDependencies.zod,
    rolldown: pkg.devDependencies.rolldown,
  },
  lockSha256: createHash("sha256").update(lock).digest("hex"),
  timing: {
    warmups: 1,
    samples: 5,
    statistic: "median",
    scope:
      "complete layout(), excluding module import, rendering and serialization",
  },
  bundles: await bundleSizes(),
  maps: [],
};
const inputs = [
  ...bookMaps(),
  {
    id: "coffee",
    manual: coffeeManual(),
    note: "A new coffee-shop map. The hand layout was drawn independently, not generated by either engine.",
  },
];
for (const { id, manual, note } of inputs) {
  const source = stripGeometry(manual);
  if (/[\u0400-\u052f]/u.test(JSON.stringify(source)))
    throw new Error(`${id}: comparison text must be English`);
  validateReferences(source);
  const entry = { id, title: manual.title, note, variants: {} };
  entry.variants.manual = { metrics: geometryMetrics(manual), timing: null };
  const variants = { manual };
  // Alternate order across maps to avoid always measuring one engine first.
  const engines = [
    ["dagre", dagreEngine],
    ["elk", elkEngine],
  ];
  if (report.maps.length % 2) engines.reverse();
  for (const [name, engine] of engines) {
    const warm = await layout(source, engine),
      serialized = JSON.stringify(warm),
      samples = [];
    for (let i = 0; i < report.timing.samples; i++) {
      const start = performance.now();
      const resolved = await layout(source, engine);
      samples.push(performance.now() - start);
      if (JSON.stringify(resolved) !== serialized)
        throw new Error(`${id}/${name}: nondeterministic layout`);
    }
    if (name === "elk") {
      const positions = Object.values(warm.edges)
        .filter((e) => e.label?.text)
        .map((e) => e.label.at.map((n) => n.toFixed(5)).join(","));
      if (new Set(positions).size !== positions.length)
        throw new Error(
          `${id}: ELK returned a shared position for different edge labels`,
        );
    }
    variants[name] = warm;
    entry.variants[name] = {
      metrics: geometryMetrics(warm),
      timing: {
        samples,
        median: [...samples].sort((a, b) => a - b)[2],
        min: Math.min(...samples),
        max: Math.max(...samples),
      },
    };
  }
  writeFileSync(
    `${destination}/data/${id}-source.json`,
    JSON.stringify(source, null, 2) + "\n",
  );
  for (const [name, map] of Object.entries(variants)) {
    writeFileSync(
      `${destination}/data/${id}-${name}.json`,
      JSON.stringify(map, null, 2) + "\n",
    );
    writeFileSync(
      `${destination}/svg/${id}-${name}.svg`,
      graphSvg(map, `${id}-${name}`, true),
    );
  }
  entry.scenarios = manual.scenarios.map((s) => ({ id: s.id, label: s.label }));
  entry.html = page.mapSection(entry, variants);
  report.maps.push(entry);
  console.log(
    `${id}: dagre ${entry.variants.dagre.timing.median.toFixed(1)} ms; ELK ${entry.variants.elk.timing.median.toFixed(1)} ms`,
  );
}
writeFileSync(`${destination}/index.html`, page.document(report));
writeFileSync(
  `${destination}/metrics.json`,
  JSON.stringify(
    { ...report, maps: report.maps.map(({ html, ...map }) => map) },
    null,
    2,
  ) + "\n",
);
writeFileSync(`${destination}/.nojekyll`, "");
copyFileSync("css/concept-map.css", `${destination}/concept-map.css`);
copyFileSync("scripts/comparison/page.css", `${destination}/page.css`);
for (const file of ["DejaVuSans.ttf", "DejaVuSansMono.ttf", "LICENSE.txt"])
  copyFileSync(`test/fixtures/fonts/${file}`, `${destination}/fonts/${file}`);
await build({
  input: "scripts/comparison/client.mjs",
  platform: "browser",
  external: [],
  output: { file: `${destination}/client.js`, minify: true },
  write: true,
});
console.log(
  `Built ${report.maps.length} comparisons → ${destination}/index.html`,
);

// Copy runnable CDN pages unchanged: no bundler or generated geometry.
cpSync("examples", `${destination}/examples`, { recursive: true });
